  async function downloadBackup() {
    try {
      const response = await fetch("/api/backup", {
        headers: passwordHeaders(),
      });
      if (!response.ok) throw new Error((await response.json()).error);
      const url = URL.createObjectURL(await response.blob());
      const link = Object.assign(document.createElement("a"), {
        href: url,
        download: "ytops-workspace-backup.json",
      });
      link.click();
      URL.revokeObjectURL(url);
      notify("Đã xuất bản sao lưu workspace.");
    } catch (error) {
      notify(error.message || "Không thể xuất bản sao lưu.", false);
    }
  }
  async function restoreBackup(file) {
    try {
      const workspace = JSON.parse(await file.text());
      if (
        !confirm(
          "Khôi phục sẽ thay thế workspace hiện tại. Hệ thống sẽ tạo bản sao lưu trước khi thay thế. Tiếp tục?",
        )
      )
        return;
      const response = await fetch("/api/restore", {
        method: "POST",
        headers: passwordHeaders({ "Content-Type": "application/json" }),
        body: JSON.stringify({ workspace }),
      });
      const data = await response.json();
      if (!response.ok) throw new Error(data.error);
      notify(data.message || "Đã khôi phục workspace.");
      location.reload();
    } catch (error) {
      notify(
        error instanceof SyntaxError
          ? "Tệp JSON không hợp lệ."
          : error.message || "Không thể khôi phục bản sao lưu.",
        false,
      );
    }
  }
