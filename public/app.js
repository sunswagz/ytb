  function translate() {
    document.title = text[document.title] || document.title;
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
    );
    const nodes = [];
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (
        !node.parentElement ||
        ["SCRIPT", "STYLE"].includes(node.parentElement.tagName)
      )
        continue;
      nodes.push(node);
    }
    for (const node of nodes) {
      let value = node.nodeValue;
      for (const [from, to] of Object.entries(text))
        value = value.replaceAll(from, to);
      node.nodeValue = value;
    }
    document.querySelectorAll("[placeholder],[value]").forEach((element) => {
      for (const attribute of ["placeholder", "value"]) {
        const value = element.getAttribute(attribute);
        if (attributes[value])
          element.setAttribute(attribute, attributes[value]);
      }
    });
  }
